use super::mir::*;
use std::fmt::Write;

/// Transpiles SSA Basic Blocks into optimized, unboxed ISO C99 / GNU C code
pub struct MirCTranspiler;

impl MirCTranspiler {
    pub fn compile_module_to_c(module: &MirModule) -> String {
        let mut out = String::new();
        out.push_str("/* Generated by Elaichi SSA Compiler */\n");
        out.push_str("#include <stdint.h>\n#include <stdbool.h>\n#include <stdio.h>\n#include <math.h>\n\n");

        // Forward declarations
        for func in &module.functions {
            let _ = writeln!(out, "int64_t {}({});", func.name, Self::format_params(func));
        }
        out.push('\n');

        // Function bodies
        for func in &module.functions {
            out.push_str(&Self::compile_function(func));
            out.push('\n');
        }

        out
    }

    fn format_params(func: &MirFunction) -> String {
        if func.params.is_empty() {
            return "void".to_string();
        }
        func.params
            .iter()
            .map(|(reg, _)| format!("int64_t r{}", reg.0))
            .collect::<Vec<_>>()
            .join(", ")
    }

    pub fn compile_function(func: &MirFunction) -> String {
        let mut out = String::new();
        let _ = writeln!(
            out,
            "int64_t {}({}) {{",
            func.name,
            Self::format_params(func)
        );

        // Pre-declare all SSA registers as pure 64-bit machine words
        if func.reg_counter > 0 {
            let reg_decls: Vec<String> = (0..func.reg_counter)
                .map(|i| format!("r{}", i))
                .collect();
            let _ = writeln!(out, "    int64_t {};", reg_decls.join(", "));
        }

        // Emit blocks with labels and goto control flow
        for (idx, block) in func.blocks.iter().enumerate() {
            let _ = writeln!(out, "bb{}:", block.id.0);

            for inst in &block.instructions {
                match inst {
                    MirInst::Const { dst, val, .. } => match val {
                        MirConst::Int(n) => {
                            let _ = writeln!(out, "    r{} = {};", dst.0, n);
                        }
                        MirConst::Float(f) => {
                            let _ = writeln!(out, "    r{} = (int64_t){};", dst.0, f);
                        }
                        MirConst::Bool(b) => {
                            let _ = writeln!(out, "    r{} = {};", dst.0, if *b { 1 } else { 0 });
                        }
                        MirConst::Str(_) => {
                            let _ = writeln!(out, "    r{} = 0; /* str ref */", dst.0);
                        }
                    },
                    MirInst::Binary { dst, op, lhs, rhs, .. } => {
                        let op_str = match op {
                            MirBinOp::Add => "+",
                            MirBinOp::Sub => "-",
                            MirBinOp::Mul => "*",
                            MirBinOp::Div => "/",
                            MirBinOp::Mod => "%",
                            MirBinOp::Eq => "==",
                            MirBinOp::Neq => "!=",
                            MirBinOp::Lt => "<",
                            MirBinOp::Lte => "<=",
                            MirBinOp::Gt => ">",
                            MirBinOp::Gte => ">=",
                        };
                        let _ = writeln!(out, "    r{} = r{} {} r{};", dst.0, lhs.0, op_str, rhs.0);
                    }
                    MirInst::Neg { dst, src, .. } => {
                        let _ = writeln!(out, "    r{} = -r{};", dst.0, src.0);
                    }
                    MirInst::Not { dst, src } => {
                        let _ = writeln!(out, "    r{} = !r{};", dst.0, src.0);
                    }
                    MirInst::Call { dst, callee, args, .. } => {
                        let formatted_args: Vec<String> =
                            args.iter().map(|r| format!("r{}", r.0)).collect();
                        let _ = writeln!(
                            out,
                            "    r{} = {}({});",
                            dst.0,
                            callee,
                            formatted_args.join(", ")
                        );
                    }
                    _ => {}
                }
            }

            match &block.terminator {
                MirTerminator::Goto(target) => {
                    let _ = writeln!(out, "    goto bb{};", target.0);
                }
                MirTerminator::Branch { cond, then_block, else_block } => {
                    let _ = writeln!(
                        out,
                        "    if (r{}) goto bb{}; else goto bb{};",
                        cond.0, then_block.0, else_block.0
                    );
                }
                MirTerminator::Return(Some(reg)) => {
                    let _ = writeln!(out, "    return r{};", reg.0);
                }
                MirTerminator::Return(None) => {
                    let _ = writeln!(out, "    return 0;");
                }
                MirTerminator::Unreachable => {
                    if idx + 1 < func.blocks.len() {
                        let next_bb = func.blocks[idx + 1].id.0;
                        let _ = writeln!(out, "    goto bb{};", next_bb);
                    } else {
                        let _ = writeln!(out, "    return 0;");
                    }
                }
            }
        }

        out.push_str("}\n");
        out
    }
}
